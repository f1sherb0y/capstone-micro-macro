class BankQuoteReaderSettings(StrictRecord):
    bank_request: RoleContractInvocation
    recipient_context: ActionContext
    identity: TaskIdentity
    source_record_sha256: Digest
    source_result_sha256: Digest
    source_reading_sha256: Digest
    shared_source_refs: Annotated[list[Reference], Field(min_length=1)]
    sharing_authorized: bool

    @field_validator('identity', mode='before')
    @classmethod
    def original_identity(cls, value):
        return TaskIdentity(**value) if isinstance(value, dict) else value


class BankQuoteReader:
    """Read a local original decision; registered offers remain independent facts.

    The application supplies original persistent components, current Bank guard
    and independent lawful sharing validation. Actual registration/reception,
    status, borrower, exact terms and reservation policy remain checked by the
    Owner handoff and its receiver validator. No action, model, offer, lending
    reservation, acceptance or funding is generated by reading the journal.

    The complete original archive is returned intact. Every original source
    must therefore appear in shared_source_refs, and validate_sharing must
    authorize that complete saved record for the exact recipient.
    """

    SETTINGS_TYPE = BankQuoteReaderSettings
    WORKER_TYPE = BankQuoteResultWorker
    ASSEMBLER_TYPE = BankQuoteActionAssembler
    SAVED_TYPE = SavedBankQuote
    SOURCE_ACTION_ID = 'BANK-A04'
    RECIPIENT_ACTION_ID = 'OWN-A05'
    EXPECTED_CHOICES = frozenset({'offer', 'conditional_offer'})

    def __init__(self, *, settings, worker, assembler, read_guard, validate_sharing):
        self.settings = self.SETTINGS_TYPE.model_validate(settings).model_copy(deep=True)
        self.worker, self.assembler = worker, assembler
        self.read_guard, self.validate_sharing = read_guard, validate_sharing
        if (not isinstance(worker, self.WORKER_TYPE) or not isinstance(assembler, self.ASSEMBLER_TYPE)
                or not callable(read_guard) or not callable(validate_sharing)):
            raise ValueError('Quotation reader requires original formal Bank components and sharing validator')
        self._settings_sha256 = task_digest(self.settings.model_dump(mode='json'))
        self._components = self._current_components()
        self._dependency_configuration = self._dependency_evidence()
        self._check()

    def _current_components(self):
        worker, assembler = self.worker, self.assembler
        return (worker, assembler, worker.store, worker.snapshots, worker.registry,
            assembler.organizations, assembler.provider, self.read_guard, self.validate_sharing)

    def _check(self):
        settings, worker, assembler = self.settings, self.worker, self.assembler
        own, recipient, identity = settings.bank_request.context, settings.recipient_context, settings.identity
        if (any(now is not original for now, original in zip(self._current_components(), self._components))
                or self._dependency_evidence() != self._dependency_configuration
                or task_digest(settings.model_dump(mode='json')) != self._settings_sha256
                or worker.ACTION_ID != self.SOURCE_ACTION_ID or assembler.ACTION_ID != self.SOURCE_ACTION_ID
                or assembler.source_mode != 'formal' or assembler.registry is not worker.registry
                or assembler._views.provider is not assembler.provider or worker.snapshots.store is not worker.store
                or worker.store.path is None or worker.store.run_id != identity.run_id
                or assembler.organizations.run_id != identity.run_id or own.run_id != identity.run_id
                or recipient.run_id != identity.run_id or identity.role != 'Bank'
                or identity.action_id != self.SOURCE_ACTION_ID or identity.purpose != 'action'
                or own.contract_ref.id != self.SOURCE_ACTION_ID or recipient.contract_ref.id != self.RECIPIENT_ACTION_ID
                or own.execution_mode != 'llm' or recipient.execution_mode != 'llm'
                or own.scope != recipient.scope or own.business_time != recipient.business_time
                or settings.sharing_authorized is not True
                or len({ref.key() for ref in settings.shared_source_refs}) != len(settings.shared_source_refs)):
            raise TaskConflict('Quotation reader changes original components, authority or sharing selection')
        grants = assembler.organizations.grants(own, self.SOURCE_ACTION_ID, 'Bank')
        if grants[0].organization_id != identity.organization_id:
            raise TaskConflict('Quotation reader changes original authorized lender organization')

    def _dependency_evidence(self):
        callbacks = {'read': self.read, 'saved_validation': self._validate_saved,
            'required_shared_refs': self.required_shared_refs, 'read_guard': self.read_guard,
            'sharing': self.validate_sharing, 'assembly': self.assembler.build,
            'completed_result': self.worker.read_completed}
        return {'schema_version': 'bank-owner-original-reader-config.v2',
            'disclosure_scope': 'complete_original_archive',
            'reader_settings_sha256': task_digest(self.settings.model_dump(mode='json')),
            'source_action_id': self.SOURCE_ACTION_ID, 'recipient_action_id': self.RECIPIENT_ACTION_ID,
            'expected_choices': sorted(self.EXPECTED_CHOICES),
            'implementations': {name: callable_implementation(callback) for name, callback in callbacks.items()}}

    def configuration_evidence(self):
        """Return pinned actual dependencies; no journal, model or native query."""
        self._check()
        return deepcopy(self._dependency_configuration)

    def required_shared_refs(self, saved):
        return {saved.action_input.application_ref.key()}

    def _validate_saved(self, saved, reading):
        settings = self.settings
        refs = {ref.key() for ref in settings.shared_source_refs}
        originals = {Reference.model_validate(row['ref']).key() for row in saved.source_reading}
        if (not isinstance(saved, self.SAVED_TYPE) or saved.identity.as_dict() != settings.identity.as_dict()
                or saved.current_context != settings.bank_request.context
                or saved.action_input.model_dump(mode='json') != settings.bank_request.action_input
                or saved.record_sha256 != settings.source_record_sha256
                or task_digest(saved.result.model_dump(mode='json')) != settings.source_result_sha256
                or saved.source_reading_sha256 != settings.source_reading_sha256
                or saved.audit['reading'].get('source_mode') != 'formal' or saved.result.kind != 'completed'
                or saved.result.payload.choice not in self.EXPECTED_CHOICES
                or refs != originals or not self.required_shared_refs(saved) <= refs):
            raise TaskConflict('Quotation reader substitutes original terms, application or shared sources')
        for row in saved.source_reading:
            if reading.resolve(Reference.model_validate(row['ref'])).model_dump(mode='json') != row['projection']:
                raise TaskConflict('Original quotation source differs from current authorized Bank source')
        reading.recheck()
        if self.validate_sharing(saved=deepcopy(saved), context=settings.recipient_context.model_copy(deep=True),
                shared_source_refs=deepcopy(settings.shared_source_refs)) is not True:
            raise TaskConflict('Application did not confirm actual Bank quotation sharing permission')
        self._check()
        return True

    def read(self, *, context, source_task_sha256):
        self._check()
        settings = self.settings
        if ActionContext.model_validate(context) != settings.recipient_context or source_task_sha256 != settings.identity.key:
            raise TaskConflict('Quotation reader requires exact current Owner recipient and original Bank task')
        with self.read_guard(settings.bank_request.context.model_copy(deep=True)):
            self._check()
            prepared = self.assembler.build(settings.bank_request.context, **deepcopy(settings.bank_request.action_input))
            try:
                saved = self.worker.read_completed(settings.identity, current_context=settings.bank_request.context,
                    reading=prepared.reading,
                    execution_versions=prepared_action_execution_versions(prepared,
                        client_version=self.worker.client_version, model_version=self.worker.model_version),
                    validate_current=lambda value: self._validate_saved(value, prepared.reading))
                return deepcopy(saved)
            finally:
                prepared.reading.recheck()
                self._check()
                if task_digest(prepared.reading.evidence()) != prepared.reading_sha256:
                    raise TaskConflict('Quotation reader changed original current Bank source snapshot')


def bind_financing_offer_sources(*, sources, reader, validate_reception, version):
    """Pair an original Bank quote reader and actual Owner offer-reception validator."""
    return _bind_bank_owner_sources(sources=sources, reader=reader, validate_reception=validate_reception, version=version,
        source_action='BANK-A04', recipient_action='OWN-A05', reader_field='read_bank_quote',
        validator_field='validate_financing_offer_reception', schema_version='v5-financing-offer-source-binding.v2',
        evidence_field='v5_financing_offer_binding')


def _bind_bank_owner_sources(*, sources, reader, validate_reception, version, source_action,
        recipient_action, reader_field, validator_field, schema_version, evidence_field):
    if (not isinstance(sources, OwnerRoleContractSources) or not isinstance(reader, BankQuoteReader)
            or reader.SOURCE_ACTION_ID != source_action or reader.RECIPIENT_ACTION_ID != recipient_action
            or not callable(validate_reception) or not isinstance(version, str) or not version.strip()):
        raise ValueError('Offer binding requires actual Owner sources, original Bank reader, validator and version')
    if getattr(sources, reader_field) is not None or getattr(sources, validator_field) is not None:
        raise TaskConflict('Offer binding cannot replace existing application callbacks')
    recipient = reader.settings.recipient_context.model_copy(deep=True)

    def components():
        return (sources.store, sources.registry, sources.organizations, sources.provider,
            sources.read_guard, sources.validators, sources.evidence, sources.model_host,
            reader, validate_reception)

    original_components = components()

    def declaration():
        return {'schema_version': schema_version, 'run_id': recipient.run_id,
            'recipient_context_sha256': task_digest(recipient.model_dump(mode='json')),
            'reader_settings_sha256': task_digest(reader.settings.model_dump(mode='json')),
            'original_reader_configuration': reader.configuration_evidence(),
            'reader': module_factory_descriptor(reader.read, reader_field),
            'receiver_validator': module_factory_descriptor(validate_reception, validator_field),
            'receiver_validator_implementation': callable_implementation(validate_reception),
            'bound_source_version': version}

    declared = declaration()

    def check_binding():
        if (any(current is not original for current, original in zip(components(), original_components))
                or declaration() != declared):
            raise TaskConflict('Bank reception binding changed original resources or actual dependency declarations')
        if sources.store.run_id != recipient.run_id or sources.organizations.run_id != recipient.run_id:
            raise TaskConflict('Offer binding changes original recipient run')
        registration = sources.registry.get(recipient_action)
        grants = sources.organizations.grants(recipient, recipient_action, 'Owner')
        if registration.role != 'Owner' or not registration.implemented or registration.skill is None:
            raise TaskConflict('Offer binding requires current Owner financing authority and original Skill')
        return grants[0].organization_id

    recipient_org = check_binding()

    def check_context(context):
        if check_binding() != recipient_org or ActionContext.model_validate(context) != recipient:
            raise TaskConflict('Bank reception changes original current Owner authority')

    def read(*, context, source_task_sha256):
        check_context(context)
        try:
            return reader.read(context=context, source_task_sha256=source_task_sha256)
        finally:
            check_context(context)

    def reception(**payment):
        check_context(payment['context'])
        saved = payment['saved']
        if not isinstance(saved, reader.SAVED_TYPE) or saved.identity.as_dict() != reader.settings.identity.as_dict():
            raise TaskConflict('Bank reception substitutes the selected original Bank task')
        # The original Owner host already holds its source guard. Preserve it
        # rather than requiring the application boundary to be reentrant.
        try:
            return validate_reception(**deepcopy(payment)) is True
        finally:
            check_context(payment['context'])

    def evidence():
        if check_binding() != recipient_org:
            raise TaskConflict('Offer binding changes original recipient organization')
        original = sources.evidence()
        if not isinstance(original, dict) or evidence_field in original:
            raise TaskConflict('Offer binding requires original application evidence without collision')
        if check_binding() != recipient_org:
            raise TaskConflict('Offer evidence changed current recipient authority')
        return {**deepcopy(original), evidence_field: {
            **deepcopy(declared), 'recipient_organization_id': recipient_org}}

    return replace(sources, version=version, evidence=evidence,
        **{reader_field: read, validator_field: reception})
