def data_for(evidence):
    return {'thoughts':'','decision':'bid','reason':'资料未知，仅提出方案。','content':'拟作为单一责任方准备方案。',
       'unresolved_condition_ids':[],'verified_condition_ids':[],'bid_assumptions':[],
       'company_assessment':unknown_assessment(evidence)}

class RepairClient:
    def __init__(self,answers):
        self.answers=answers; self.messages=[]
    async def achat(self,messages,temperature=.2):
        self.messages.append(deepcopy(messages))
        assert len(self.messages)<=len(self.answers),'Unexpected extra retry'
        return self.answers[len(self.messages)-1]

def test_targeted_reference_repair_preserves_original_answer_and_strategy():
    e=company_evidence({'company_id':'SYNTHETIC-c'})
    good=data_for(e); bad=deepcopy(good)
    bad['company_assessment']['company_id']='foreign'
    client=RepairClient([json.dumps(bad),json.dumps(good)])
    runtime=AgentRuntime(client,company_grounding=True,company_narrative_grounding=True)
    result=asyncio.run(runtime.ask_json_async('fixture','MANAGEMENT_DECISION','fixture',
        validator=guarded_validator(require_management_decision,[],company_sources=e,narrative_grounding=True)))
    assert len(client.messages)==2
    assert client.messages[1][-2]=={'role':'assistant','content':json.dumps(bad)}
    assert 'company_assessment' in client.messages[1][-1]['content']
    assert result['decision']=='bid'
    assert runtime.response_attempts[0]['original_parsed']==bad
    assert runtime.response_attempts[1]['repair_diff']['unexpected_changed_paths']==[]

