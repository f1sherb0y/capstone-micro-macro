class BadSourceClient(SourceFixtureClient):
    final_calls=0
    async def achat(self,messages,temperature=.2):
        if messages[1]['content'].startswith('AGENT_MESSAGE'):
            return await super().achat(messages,temperature)
        self.final_calls+=1
        data=json.loads(await super().achat(messages,temperature))
        key='technical_proposal' if messages[1]['content'].startswith('BID_DOCUMENT') else 'content'
        data[key]='本公司具备完整专业能力。'
        return json.dumps(data,ensure_ascii=False)

@pytest.mark.parametrize('stage',['management','reconsideration','bid'])
@pytest.mark.parametrize('invalid',[False,True])
def test_real_stages_checkpoint_review_or_pending_without_forced_no_bid(stage,invalid):
    state=solo_state()
    client=BadSourceClient() if invalid else SourceFixtureClient()
    runtime=AgentRuntime(client,profile='smoke',company_grounding=True,company_narrative_grounding=True)
    assert runtime.isolated_clone().company_narrative_grounding
    if stage=='management':
        asyncio.run(run_bid_participation(state,runtime))
    elif stage=='reconsideration':
        state.participation_decisions=[ParticipationDecision('designer_001','design_package','bid_with_consortium','unformed')]
        asyncio.run(reconsider_after_failed_consortiums(state,runtime))
    else:
        state.participation_decisions=[ParticipationDecision('designer_001','design_package','bid','proposal')]
        asyncio.run(generate_bid_documents(state,runtime))
    restored=load_simulation_state(dump(state))
    assert not restored.verification_reviews
    if invalid:
        assert client.final_calls==2
        assert restored.validation_context['micro_output_pending']
        assert all(p.decision!='no_bid' for p in restored.participation_decisions)
        if stage=='management':
            assert not restored.participation_decisions
        if stage=='bid':
            assert not restored.bid_documents
    else:
        product=restored.bid_documents[0] if stage=='bid' else restored.participation_decisions[0]
        report=product.company_narrative_review
        assert report['status']=='limited_checks_passed'
        assert report['original_outward']==report['adopted_outward']
        assert not restored.validation_context.get('micro_output_pending')

