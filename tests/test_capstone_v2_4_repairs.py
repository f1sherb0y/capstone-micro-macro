@pytest.fixture(autouse=True)
def no_provider(monkeypatch):
    def deny(*a,**k):
        raise AssertionError('V2.4 offline fixtures forbid network/provider construction')
    # Windows creates a loopback socketpair when making the event loop.
    # Initialize that local primitive BEFORE the same strict network block
    # used by the prior offline batch, rather than allowing loopback requests.
    with asyncio.Runner() as runner:
        runner.get_loop()
        monkeypatch.setattr(asyncio,'run',lambda coroutine:runner.run(coroutine))
        monkeypatch.setattr(socket.socket,'connect',deny)
        monkeypatch.setattr(socket.socket,'connect_ex',deny)
        monkeypatch.setattr('src.llm_client.OpenAICompatibleClient.from_env',deny)
        yield

